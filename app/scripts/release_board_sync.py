#!/usr/bin/env python3
from __future__ import annotations

import argparse
import json
import re
import sys
from datetime import UTC, datetime
from pathlib import Path
from typing import Any, Optional

ROOT = Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from app.scripts import release_evidence_summary as release_summary

DEFAULT_BOARD_PATH = ROOT / "docs" / "release_board.md"
DEFAULT_EVIDENCE_ROOT = ROOT / "artifacts" / "release_evidence"
DEFAULT_CORE_EVIDENCE_ROOT = ROOT / "artifacts" / "release_evidence_core"
BEGIN_MARKER = "<!-- BEGIN AUTO RELEASE EVIDENCE -->"
END_MARKER = "<!-- END AUTO RELEASE EVIDENCE -->"
CORE_BEGIN_MARKER = "<!-- BEGIN AUTO CORE RELEASE EVIDENCE -->"
CORE_END_MARKER = "<!-- END AUTO CORE RELEASE EVIDENCE -->"
_BUNDLE_DIR_RE = re.compile(r"^\d{8}_\d{6}$")


def find_latest_bundle(evidence_root: Path) -> Optional[Path]:
    root = evidence_root.resolve()
    if not root.exists() or not root.is_dir():
        return None
    candidates = sorted(
        (path for path in root.iterdir() if path.is_dir() and _BUNDLE_DIR_RE.match(path.name)),
        key=lambda path: path.name,
        reverse=True,
    )
    return candidates[0] if candidates else None


def _load_summary_from_file(path: Path) -> Optional[dict[str, Any]]:
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
    except Exception:
        return None
    return payload if isinstance(payload, dict) else None


def _relative_display(path: Path) -> str:
    try:
        return str(path.resolve().relative_to(ROOT))
    except Exception:
        return str(path.resolve())


def _format_bundle_stamp(bundle_dir: Optional[Path]) -> str:
    if bundle_dir is None:
        return "n/a"
    name = str(bundle_dir.name or "").strip()
    if not _BUNDLE_DIR_RE.match(name):
        return name or "n/a"
    try:
        parsed = datetime.strptime(name, "%Y%m%d_%H%M%S")
    except ValueError:
        return name
    return parsed.strftime("%Y-%m-%d %H:%M:%S")


def _parse_bundle_datetime(bundle_dir: Optional[Path]) -> Optional[datetime]:
    if bundle_dir is None:
        return None
    name = str(bundle_dir.name or "").strip()
    if not _BUNDLE_DIR_RE.match(name):
        return None
    try:
        return datetime.strptime(name, "%Y%m%d_%H%M%S").replace(tzinfo=UTC)
    except ValueError:
        return None


def _coerce_utc(value: datetime) -> datetime:
    if value.tzinfo is None:
        return value.replace(tzinfo=UTC)
    return value.astimezone(UTC)


def _format_bundle_freshness(bundle_dir: Optional[Path], *, now: Optional[datetime] = None) -> str:
    parsed = _parse_bundle_datetime(bundle_dir)
    if parsed is None:
        return "unknown"
    reference = _coerce_utc(now) if now is not None else datetime.now(UTC)
    age_seconds = max(0.0, (reference - parsed).total_seconds())
    age_hours = age_seconds / 3600.0
    age_days = age_seconds / 86400.0
    if age_hours <= 72.0:
        label = "fresh"
    elif age_days <= 14.0:
        label = "aging"
    else:
        label = "stale"
    if age_hours < 24.0:
        age_text = f"{int(round(age_hours))}h"
    else:
        age_text = f"{int(round(age_days))}d"
    return f"{label} • age={age_text}"


def _find_latest_rehearsal_summary(bundle_dir: Path) -> Optional[Path]:
    root = bundle_dir / "crypto_testnet_rehearsal"
    direct = root / "summary.json"
    if direct.exists() and direct.is_file():
        return direct
    if not root.exists() or not root.is_dir():
        return None
    candidates = sorted((path for path in root.glob("*/summary.json") if path.is_file()), key=lambda path: path.parent.name, reverse=True)
    return candidates[0] if candidates else None


def _replace_marked_block(text: str, *, begin_marker: str, end_marker: str, rendered: str) -> str:
    before, marker, rest = text.partition(begin_marker)
    if not marker:
        raise ValueError(f"Missing marker: {begin_marker}")
    _middle, end, after = rest.partition(end_marker)
    if not end:
        raise ValueError(f"Missing marker: {end_marker}")
    return before + rendered + after


def build_latest_evidence_snapshot(
    evidence_root: Path = DEFAULT_EVIDENCE_ROOT,
    *,
    track: str = "full",
    now: Optional[datetime] = None,
) -> str:
    normalized_track = str(track or "full").strip().lower() or "full"
    is_core = normalized_track == "core"
    begin_marker = CORE_BEGIN_MARKER if is_core else BEGIN_MARKER
    end_marker = CORE_END_MARKER if is_core else END_MARKER
    bundle_label = "core" if is_core else "full"
    latest_bundle = find_latest_bundle(evidence_root)
    lines = [
        begin_marker,
        "_Generated by `python -m app.scripts.release_board_sync`._",
    ]

    if latest_bundle is None:
        lines.extend(
            [
                f"- Latest {bundle_label} bundle: `missing`",
                "- Bundle stamp: `n/a`",
                "- Bundle freshness: `unknown`",
                "- Summary source: `none`",
                "- Overall: `UNKNOWN`",
                "- Checks: `0/0` passed",
                "- Failed gates: `none`",
            ]
        )
        if is_core:
            lines.append("- Optional soak gate: `not-run`")
        else:
            lines.append("- Crypto testnet rehearsal: `missing`")
        lines.append(end_marker)
        return "\n".join(lines) + "\n"

    summary_file = latest_bundle / "release_summary.json"
    summary_payload = _load_summary_from_file(summary_file) if summary_file.exists() else None
    summary_source = _relative_display(summary_file) if summary_payload is not None else "computed from latest bundle"
    if summary_payload is None:
        summary_payload = release_summary.summarize_bundle(latest_bundle, track=normalized_track)

    checks = summary_payload.get("checks") if isinstance(summary_payload.get("checks"), list) else []
    failed_names = [str(row.get("name") or "unknown") for row in checks if not bool(row.get("ok"))]
    passed_checks = int(summary_payload.get("passed_checks") or 0)
    total_checks = int(summary_payload.get("total_checks") or 0)
    overall_ok = bool(summary_payload.get("ok"))
    rehearsal_check = next((row for row in checks if str(row.get("name") or "") == "crypto_testnet_rehearsal"), None)
    rehearsal_summary = _find_latest_rehearsal_summary(latest_bundle)

    lines.extend(
        [
            f"- Latest {bundle_label} bundle: `{_relative_display(latest_bundle)}`",
            f"- Bundle stamp: `{_format_bundle_stamp(latest_bundle)}`",
            f"- Bundle freshness: `{_format_bundle_freshness(latest_bundle, now=now)}`",
            f"- Summary source: `{summary_source}`",
            f"- Overall: `{'PASS' if overall_ok else 'FAIL'}`",
            f"- Checks: `{passed_checks}/{total_checks}` passed",
            f"- Failed gates: `{', '.join(failed_names) if failed_names else 'none'}`",
        ]
    )

    if is_core:
        soak_check = next((row for row in checks if str(row.get("name") or "") == "soak_gate_core"), None)
        if isinstance(soak_check, dict):
            detail = str(soak_check.get("detail") or "").strip() or "n/a"
            lines.append(f"- Optional soak gate: `{'PASS' if bool(soak_check.get('ok')) else 'FAIL'}` • {detail}")
        else:
            lines.append("- Optional soak gate: `not-run`")
    else:
        if isinstance(rehearsal_check, dict):
            detail = str(rehearsal_check.get("detail") or "").strip() or "n/a"
            lines.append(f"- Crypto testnet rehearsal: `{'PASS' if bool(rehearsal_check.get('ok')) else 'FAIL'}` • {detail}")
        elif rehearsal_summary is not None:
            lines.append(f"- Crypto testnet rehearsal: `artifact present, summary not scored` • `{_relative_display(rehearsal_summary)}`")
        else:
            lines.append("- Crypto testnet rehearsal: `missing`")

    lines.append(end_marker)
    return "\n".join(lines) + "\n"


def update_release_board(
    board_path: Path = DEFAULT_BOARD_PATH,
    *,
    evidence_root: Path = DEFAULT_EVIDENCE_ROOT,
    core_evidence_root: Path = DEFAULT_CORE_EVIDENCE_ROOT,
) -> Path:
    target = board_path.resolve()
    text = target.read_text(encoding="utf-8")
    rendered_full = build_latest_evidence_snapshot(evidence_root, track="full")
    rendered_core = build_latest_evidence_snapshot(core_evidence_root, track="core")
    text = _replace_marked_block(text, begin_marker=BEGIN_MARKER, end_marker=END_MARKER, rendered=rendered_full)
    text = _replace_marked_block(text, begin_marker=CORE_BEGIN_MARKER, end_marker=CORE_END_MARKER, rendered=rendered_core)
    target.write_text(text, encoding="utf-8")
    return target


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Sync the generated evidence snapshot inside docs/release_board.md.")
    parser.add_argument("--board-path", default=str(DEFAULT_BOARD_PATH))
    parser.add_argument("--evidence-root", default=str(DEFAULT_EVIDENCE_ROOT))
    parser.add_argument("--core-evidence-root", default=str(DEFAULT_CORE_EVIDENCE_ROOT))
    parser.add_argument("--track", choices=["full", "core", "both"], default="both")
    parser.add_argument("--print-only", action="store_true", help="Print the generated evidence section instead of writing the board file.")
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    evidence_root = Path(args.evidence_root).resolve()
    core_evidence_root = Path(args.core_evidence_root).resolve()
    if args.print_only:
        if args.track == "full":
            sys.stdout.write(build_latest_evidence_snapshot(evidence_root, track="full"))
        elif args.track == "core":
            sys.stdout.write(build_latest_evidence_snapshot(core_evidence_root, track="core"))
        else:
            sys.stdout.write(build_latest_evidence_snapshot(evidence_root, track="full"))
            sys.stdout.write("\n")
            sys.stdout.write(build_latest_evidence_snapshot(core_evidence_root, track="core"))
        return 0
    target = update_release_board(Path(args.board_path), evidence_root=evidence_root, core_evidence_root=core_evidence_root)
    print(f"[ok] synced {target}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())