#!/usr/bin/env python3
from __future__ import annotations

import argparse
import json
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Dict, Iterable, List


ROOT = Path(__file__).resolve().parents[2]


@dataclass
class CleanupResult:
    removed: List[str]
    missing: List[str]
    errors: List[str]
    bytes_removed: int

    def as_dict(self) -> Dict[str, Any]:
        return {
            "ok": len(self.errors) == 0,
            "removed_count": len(self.removed),
            "missing_count": len(self.missing),
            "error_count": len(self.errors),
            "bytes_removed": self.bytes_removed,
            "removed": self.removed,
            "missing": self.missing,
            "errors": self.errors,
        }


def _iter_runtime_artifacts(root: Path, *, include_aggressive: bool = False) -> Iterable[Path]:
    data = root / "data"
    images = data / "images"
    turns = data / "conversation_turns"
    release_evidence = root / "artifacts" / "release_evidence"

    # Image outputs + placeholder text files + image generation logs.
    for pattern in ("*.png", "*.jpg", "*.jpeg", "*.webp", "*.gif", "*.bmp", "*.txt"):
        yield from images.glob(pattern)
    yield images / "log.jsonl"

    # Turn/item traces and validation snapshots generated during runtime/tests.
    if turns.exists():
        yield from turns.rglob("*.json")
    yield data / "validation_state.json"

    # Optional extra cleanup for local demos/tests.
    if include_aggressive:
        yield data / "av_scan_events.jsonl"
        tmp_proj = data / "tmp_test_proj"
        if tmp_proj.exists():
            yield tmp_proj
        # Optional stale 72h-run control artifacts.
        yield release_evidence / "full_72h.pid"
        yield release_evidence / "full_72h.logpath"
        if release_evidence.exists():
            yield from release_evidence.glob("full_72h_*.log")


def cleanup_runtime_artifacts(
    root: Path,
    *,
    dry_run: bool = False,
    aggressive: bool = False,
) -> CleanupResult:
    removed: List[str] = []
    missing: List[str] = []
    errors: List[str] = []
    bytes_removed = 0

    seen: set[Path] = set()
    for target in _iter_runtime_artifacts(root, include_aggressive=aggressive):
        try:
            target = target.resolve()
        except Exception:
            continue
        if target in seen:
            continue
        seen.add(target)

        rel = str(target.relative_to(root)) if target.is_absolute() and root in target.parents else str(target)
        if not target.exists():
            missing.append(rel)
            continue

        try:
            if target.is_dir():
                size = 0
                for p in target.rglob("*"):
                    if p.is_file():
                        try:
                            size += p.stat().st_size
                        except Exception:
                            pass
                if not dry_run:
                    for p in sorted(target.rglob("*"), reverse=True):
                        if p.is_file():
                            p.unlink(missing_ok=True)
                        elif p.is_dir():
                            try:
                                p.rmdir()
                            except Exception:
                                pass
                    target.rmdir()
                bytes_removed += size
                removed.append(rel)
                continue

            size = target.stat().st_size
            if not dry_run:
                target.unlink(missing_ok=True)
            bytes_removed += size
            removed.append(rel)
        except Exception as exc:  # noqa: BLE001
            errors.append(f"{rel}: {exc}")

    return CleanupResult(
        removed=removed,
        missing=missing,
        errors=errors,
        bytes_removed=bytes_removed,
    )


def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(description="Cleanup runtime artifacts generated by AEGIS demos/tests.")
    p.add_argument("--dry-run", action="store_true", help="Show what would be removed without deleting files.")
    p.add_argument(
        "--aggressive",
        action="store_true",
        help="Also remove additional transient logs (e.g., av_scan_events, tmp_test_proj).",
    )
    return p.parse_args()


def main() -> int:
    args = parse_args()
    result = cleanup_runtime_artifacts(ROOT, dry_run=bool(args.dry_run), aggressive=bool(args.aggressive))
    print(json.dumps(result.as_dict(), ensure_ascii=False))
    return 0 if not result.errors else 1


if __name__ == "__main__":
    raise SystemExit(main())
